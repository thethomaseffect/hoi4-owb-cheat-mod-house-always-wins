"""Generate can_research passes for OWB normal and unique techs."""

from __future__ import annotations

import re
from pathlib import Path

OWB_TECH = Path(
    r"C:\Program Files (x86)\Steam\steamapps\workshop\content\394360\2265420196\common\technologies"
)
OUT = Path(__file__).resolve().parents[1] / "common" / "scripted_effects" / "haw_tech_research.txt"

NORMAL_FILES = [
    "tech_infantry.txt",
    "tech_industry.txt",
    "tech_naval.txt",
    "tech_engineering.txt",
    "tech_robotics.txt",
    "tech_support.txt",
    "tech_vehicle.txt",
    "tech_air.txt",
    "tech_creatures.txt",
    "tech_horse.txt",
    "tech_implant.txt",
    "tech_naval_modules.txt",
    "tech_tribal.txt",
    "tech_access.txt",
]

PASSES = 12
ID_RE = re.compile(r"^\t([a-zA-Z][a-zA-Z0-9_]*) = \{", re.M)
UNLOCK_DEP_RE = re.compile(r"[a-zA-Z0-9_]+_unlock_tech\s*=\s*1")


def extract_techs(text: str) -> list[tuple[str, str]]:
    matches = list(ID_RE.finditer(text))
    techs: list[tuple[str, str]] = []
    for i, match in enumerate(matches):
        name = match.group(1)
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        techs.append((name, text[match.end() : end]))
    return techs


def is_blocked(body: str) -> bool:
    if "blocked_tech" in body:
        return True
    if re.search(r"allow\s*=\s*\{\s*always\s*=\s*no", body):
        return True
    return False


def write_pass(lines: list[str], techs: list[str], indent: str = "\t") -> None:
    for tech in techs:
        lines.append(f"{indent}if = {{")
        lines.append(f"{indent}\tlimit = {{ can_research = {tech} }}")
        lines.append(f"{indent}\tset_technology = {{")
        lines.append(f"{indent}\t\tpopup = no")
        lines.append(f"{indent}\t\t{tech} = 1")
        lines.append(f"{indent}\t}}")
        lines.append(f"{indent}}}")


def main() -> None:
    unique: list[str] = []
    normal: list[str] = []
    seen: set[str] = set()

    for filename in NORMAL_FILES:
        path = OWB_TECH / filename
        text = path.read_text(encoding="utf-8", errors="replace")
        for name, body in extract_techs(text):
            if name in seen:
                continue
            seen.add(name)
            if name.endswith("_unlock_tech") or "_tech_level_" in name:
                continue
            if is_blocked(body):
                continue
            if UNLOCK_DEP_RE.search(body):
                unique.append(name)
            else:
                normal.append(name)

    lines = [
        "# Generated by tools/_gen_tech_research.py from OWB common/technologies.",
        "# Unique = techs gated by *_unlock_tech. Normal = remaining researchable items.",
        "",
        "haw_research_unique_equipment_pass = {",
    ]
    write_pass(lines, unique)
    lines.append("}")
    lines.append("")
    lines.append("haw_research_unique_equipment = {")
    for _ in range(PASSES):
        lines.append("\thaw_research_unique_equipment_pass = yes")
    lines.append("}")
    lines.append("")
    lines.append("haw_research_normal_techs_pass = {")
    write_pass(lines, normal)
    lines.append("}")
    lines.append("")
    lines.append("haw_unlock_available_normal_techs = {")
    for _ in range(PASSES):
        lines.append("\thaw_research_normal_techs_pass = yes")
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"unique={len(unique)} normal={len(normal)} -> {OUT}")


if __name__ == "__main__":
    main()
