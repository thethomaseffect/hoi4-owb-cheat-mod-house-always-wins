def write_lang(folder: str, header: str, index: int, filename: str) -> Path:
    out = ROOT / "localisation" / folder / filename
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"{header}:"]
    for key, *texts in STRINGS:
        lines.append(f' {key}:0 "{texts[index - 1]}"')
    out.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    return out


def main() -> None:
    for folder, (header, index, filename) in LANGS.items():
        path = write_lang(folder, header, index, filename)
        print("wrote", path, "bytes", path.stat().st_size)


if __name__ == "__main__":
    main()
