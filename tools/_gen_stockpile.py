"""Generate add_equipment_to_stockpile for every OWB equipment archetype."""

from __future__ import annotations

import re
from pathlib import Path

OWB_EQ = Path(
    r"C:\Program Files (x86)\Steam\steamapps\workshop\content\394360\2265420196\common\units\equipment"
)
OUT = Path(__file__).resolve().parents[1] / "common" / "scripted_effects" / "haw_stockpile.txt"

ID_RE = re.compile(r"^\t([a-zA-Z][a-zA-Z0-9_]*) = \{", re.M)


def extract_archetypes(text: str) -> list[str]:
    matches = list(ID_RE.finditer(text))
    names: list[str] = []
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        body = text[match.end() : end]
        if re.search(r"is_archetype\s*=\s*yes", body):
            names.append(match.group(1))
    return names


def main() -> None:
    seen: set[str] = set()
    archetypes: list[str] = []
    for path in sorted(OWB_EQ.glob("*.txt")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for name in extract_archetypes(text):
            if name not in seen:
                seen.add(name)
                archetypes.append(name)

    lines = [
        "# Generated by tools/_gen_stockpile.py from OWB equipment archetypes.",
        "haw_stockpile_unlocked = {",
    ]
    for name in archetypes:
        lines.append("\tadd_equipment_to_stockpile = {")
        lines.append(f"\t\ttype = {name}")
        lines.append("\t\tamount = 10000")
        lines.append("\t\tproducer = ROOT")
        lines.append("\t}")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"archetypes={len(archetypes)} -> {OUT}")


if __name__ == "__main__":
    main()
