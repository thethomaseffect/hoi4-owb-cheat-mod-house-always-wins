"""Upgrade existing road segments and put hubs on those tiles.

Railways are connection paths in map/railways.txt. Province building effects
cannot change Road Connection level; only build_railway can.
"""

from __future__ import annotations

import re
from pathlib import Path

WORKSHOP = Path(r"C:\Program Files (x86)\Steam\steamapps\workshop\content\394360")
OWB = WORKSHOP / "2265420196"
OWB_MAP = OWB / "map"
OWB_STATES = OWB / "history" / "states"
OUT_DIR = Path(__file__).resolve().parents[1] / "common" / "scripted_effects"

ID_RE = re.compile(r"id\s*=\s*(\d+)")
PROV_RE = re.compile(r"provinces\s*=\s*\{([^}]*)\}", re.S)
NUM_RE = re.compile(r"\d+")
PATH_CHUNK = 200
HUB_CHUNK = 80


def load_province_states() -> dict[int, int]:
    province_state: dict[int, int] = {}
    for path in OWB_STATES.glob("*.txt"):
        text = path.read_text(encoding="utf-8", errors="replace")
        if re.search(r"^\s*impassable\s*=\s*yes", text, re.M):
            continue
        id_match = ID_RE.search(text)
        prov_match = PROV_RE.search(text)
        if not id_match or not prov_match:
            continue
        state_id = int(id_match.group(1))
        for province in NUM_RE.findall(prov_match.group(1)):
            province_state[int(province)] = state_id
    return province_state


def load_railway_paths() -> list[list[int]]:
    paths: list[list[int]] = []
    for raw in (OWB_MAP / "railways.txt").read_text(encoding="utf-8", errors="replace").splitlines():
        nums = [int(part) for part in raw.split() if part.isdigit()]
        if len(nums) < 4:
            continue
        count = nums[1]
        provinces = nums[2 : 2 + count]
        if len(provinces) >= 2:
            paths.append(provinces)
    return paths


def wipe_old() -> None:
    for old in OUT_DIR.glob("haw_state_roads*.txt"):
        old.unlink()


def write_chunks(stem: str, effect: str, blocks: list[list[str]], chunk: int) -> list[str]:
    names: list[str] = []
    for index in range(0, len(blocks), chunk):
        name = f"{effect}_{index // chunk}"
        names.append(name)
        lines = [
            "# Generated by tools/_gen_state_roads.py from OWB map/railways.txt.",
            f"{name} = {{",
        ]
        for block in blocks[index : index + chunk]:
            lines.extend(block)
        lines.append("}")
        lines.append("")
        (OUT_DIR / f"{stem}_{index // chunk}.txt").write_text("\n".join(lines), encoding="utf-8")
    return names


def path_block(provinces: list[int]) -> list[str]:
    joined = " ".join(str(pid) for pid in provinces)
    return [
        "	build_railway = {",
        "		level = 5",
        "		build_only_on_allied = yes",
        f"		path = {{ {joined} }}",
        "	}",
    ]


def hub_state_block(state_id: int, provinces: list[int]) -> list[str]:
    lines = [
        f"	{state_id} = {{",
        "		if = {",
        "			limit = { is_owned_and_controlled_by = ROOT }",
    ]
    for province in provinces:
        lines.append(
            "			add_building_construction = { "
            f"type = supply_node level = 1 instant_build = yes province = {{ id = {province} }} }}"
        )
    lines.append("		}")
    lines.append("	}")
    return lines


def main() -> None:
    wipe_old()
    province_state = load_province_states()
    paths = load_railway_paths()
    rail_provinces = sorted({pid for path in paths for pid in path})

    path_names = write_chunks(
        "haw_state_roads",
        "haw_upgrade_map_paths",
        [path_block(path) for path in paths],
        PATH_CHUNK,
    )

    by_state: dict[int, list[int]] = {}
    for province in rail_provinces:
        state_id = province_state.get(province)
        if state_id is None:
            continue
        by_state.setdefault(state_id, []).append(province)
    hub_blocks = [
        hub_state_block(state_id, provinces)
        for state_id, provinces in sorted(by_state.items())
    ]
    hub_names = write_chunks("haw_state_roads_hubs", "haw_hubs_on_map_roads", hub_blocks, HUB_CHUNK)

    index_lines = [
        "# Generated by tools/_gen_state_roads.py",
        "haw_hubs_on_existing_roads = {",
    ]
    for name in path_names:
        index_lines.append(f"	{name} = yes")
    for name in hub_names:
        index_lines.append(f"	{name} = yes")
    index_lines.append("}")
    index_lines.append("")
    (OUT_DIR / "haw_state_roads.txt").write_text("\n".join(index_lines), encoding="utf-8")
    print(
        f"paths={len(paths)} rail_provinces={len(rail_provinces)} "
        f"hub_states={len(by_state)} files={len(path_names)+len(hub_names)}"
    )


if __name__ == "__main__":
    main()
